#!/usr/bin/env node
/*
  Concatenate supabase/migrations/ into one transactional script for the SQL
  editor, and record each version in Supabase's migration ledger.

  Why this exists instead of `supabase db push`:

  `supabase_migrations.schema_migrations` is a single table in the project's
  database, so it is shared by every repo that pushes to that project. Another
  app already owns this project's ledger (versions 0001..0005). `db push` guards
  against divergence and refuses as soon as the remote has versions the local
  directory does not, and neither --include-all nor a dry run bypasses it.

  The CLI's own suggestions are both destructive here:
    - `migration repair --status reverted 0001..0005` marks the OTHER app's
      migrations as un-applied in the shared ledger, so its repo may re-run them.
    - `db pull` copies that app's entire public schema into this repo, which is
      public.

  So: emit SQL, apply it once in the dashboard, and write our own ledger rows so
  `supabase migration list` still reports the truth.

  Usage:  node scripts/bundle-migrations.mjs > bundle.sql
*/
import { readdir, readFile } from 'node:fs/promises'
import { join } from 'node:path'

const DIR = join(process.cwd(), 'supabase/migrations')
const files = (await readdir(DIR)).filter((f) => f.endsWith('.sql')).sort()

const out = []
out.push('-- Generated by scripts/bundle-migrations.mjs. Do not edit by hand.')
out.push('-- Apply in the Supabase SQL editor. One transaction: all or nothing.')
out.push('')
out.push('begin;')
out.push('')

for (const file of files) {
  const version = file.split('_')[0]
  const name = file.replace(/^\d+_/, '').replace(/\.sql$/, '')
  const sql = await readFile(join(DIR, file), 'utf8')

  out.push(`-- ${'='.repeat(70)}`)
  out.push(`-- ${file}`)
  out.push(`-- ${'='.repeat(70)}`)
  out.push(sql.trimEnd())
  out.push('')
  // Keep `supabase migration list` honest even though db push cannot run here.
  out.push(`insert into supabase_migrations.schema_migrations (version, name)`)
  out.push(`values ('${version}', '${name}') on conflict (version) do nothing;`)
  out.push('')
}

// The search_path changes above are session scoped; leave the editor session as
// it was found so a later query in the same tab is not silently reschema'd.
out.push('reset search_path;')
out.push('')
out.push('commit;')
out.push('')

process.stdout.write(out.join('\n'))
